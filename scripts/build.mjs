// 把 effects/*/meta.json + 源码 + site/ 打包成静态站点 dist/。零依赖，Node 18+。
// 用法：node scripts/build.mjs
//   GITHUB_SHA         Prompt 里源码链接固定到的 commit（CI 自动注入；本地默认 main）
//   GITHUB_REPOSITORY  owner/repo（CI 自动注入；本地默认 cocofhu/AniMuse）
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, rmSync, cpSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'dist');
const REPO = process.env.GITHUB_REPOSITORY || 'cocofhu/AniMuse';
const REF = process.env.GITHUB_SHA || 'main';
const BUILD = Date.now().toString(36);
const [OWNER, NAME] = REPO.split('/');
const PAGES = `https://${OWNER.toLowerCase()}.github.io/${NAME}/`;

const fail = (m) => { console.error('✗ ' + m); process.exitCode = 1; };
const categories = JSON.parse(readFileSync(join(ROOT, 'site/categories.json'), 'utf8'));

const effects = readdirSync(join(ROOT, 'effects'))
  .filter((d) => statSync(join(ROOT, 'effects', d)).isDirectory())
  .map((slug) => {
    const dir = join(ROOT, 'effects', slug);
    const metaPath = join(dir, 'meta.json');
    if (!existsSync(metaPath)) { fail(`${slug}: 缺少 meta.json`); return null; }
    const meta = JSON.parse(readFileSync(metaPath, 'utf8'));
    for (const k of ['name', 'summary', 'technique', 'category', 'params', 'files']) if (!meta[k]) fail(`${slug}: meta.json 缺少 ${k}`);
    if (meta.slug !== slug) fail(`${slug}: meta.slug (${meta.slug}) 和目录名不一致`);
    if (!categories[meta.category]) fail(`${slug}: 未知分类 ${meta.category}（见 site/categories.json）`);
    if (!existsSync(join(dir, 'preview.png'))) console.warn(`! ${slug}: 还没有 preview.png（npm run previews 生成）`);
    const source = {};
    for (const f of meta.files) {
      if (!existsSync(join(dir, f))) { fail(`${slug}: files 里列了 ${f} 但文件不存在`); continue; }
      source[f] = readFileSync(join(dir, f), 'utf8');
    }
    return { ...meta, posterEn: existsSync(join(dir, 'preview.en.png')), source };
  })
  .filter(Boolean)
  .sort((a, b) => (a.order ?? 999) - (b.order ?? 999) || a.slug.localeCompare(b.slug));

if (process.exitCode) process.exit();

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
cpSync(join(ROOT, 'effects'), join(OUT, 'effects'), { recursive: true });
for (const f of ['style.css', 'app.js', 'favicon.svg', 'og.png']) if (existsSync(join(ROOT, 'site', f))) cpSync(join(ROOT, 'site', f), join(OUT, f));

const data = { repo: REPO, ref: REF, built: new Date().toISOString(), categories, effects };
writeFileSync(join(OUT, 'data.js'), '/* generated by scripts/build.mjs — do not edit */\nwindow.ANIMUSE = ' + JSON.stringify(data) + ';\n');

const html = readFileSync(join(ROOT, 'site/index.html'), 'utf8')
  .replaceAll('__REPO__', REPO).replaceAll('__PAGES__', PAGES).replaceAll('__REF7__', REF.slice(0, 7)).replaceAll('__BUILD__', BUILD);
writeFileSync(join(OUT, 'index.html'), html);
writeFileSync(join(OUT, '.nojekyll'), '');
console.log(`✓ ${effects.length} effects → dist/  (repo ${REPO} @ ${REF.slice(0, 7)})`);
